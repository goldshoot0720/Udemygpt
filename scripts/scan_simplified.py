def main():
    course_dir = Path('data/courses') / (sys.argv[1] if len(sys.argv) > 1 else '5291332')
    ledger = json.loads((course_dir / 'translation-progress.json').read_text(encoding='utf-8'))
    hits = []
    lectures = 0
    for lecture in ledger['lectures']:
        if lecture.get('status') != 'verified':
            continue
        lectures += 1
        path = course_dir / 'work' / 'results' / f"result-{lecture['lectureId']}.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding='utf-8'))
        for cue in data['lectures'][0]['cues']:
            zh = cue.get('zh', '')
            bad = sorted({ch for ch in zh if FORBIDDEN.get(ch, ch) != ch})
            if bad:
                hits.append((lecture['lectureOrder'], lecture['lectureId'], cue['id'],
                             zh, bad))
    print(f'掃描 {lectures} 堂已驗證譯文')
    if not hits:
        print('沒有發現簡體字或日本字形。')
        return 0
    print(f'發現 {len(hits)} 處問題：')
    for order, lid, cid, zh, bad in hits:
        fixed = ''.join(FORBIDDEN.get(ch, ch) for ch in zh)
        print(f'  第{order}堂 {lid} cue {cid}：{zh}')
        print(f'    → {fixed}   [{", ".join(bad)}]')
    return 1


